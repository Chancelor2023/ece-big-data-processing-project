"""Run the IMDb exploration analyses.

The Q6 language input is an external Parquet table with columns ``tconst`` and
``original_language``. Set ORIGINAL_LANGUAGE_PATH to its location. No such
source is produced by the Wikimedia recent-changes streaming pipeline; the
configured default is a placeholder until a real source is supplied.
"""
import json
import os
from pathlib import Path

from pyspark.sql import functions as F

from imdb_pipeline.config import CLEAN_DIR
from imdb_pipeline.spark import create_spark
from imdb_pipeline.tables import load_clean_tables
from jobs.exploration import analyses as A
from jobs.exploration.params import Params

OUT = Path("results/exploration")
# TODO: obtain/create a defensible source for original_language values. This
# path is only a configurable expectation, not a dataset generated by streaming.
DEFAULT_ORIGINAL_LANGUAGE_PATH = Path("data/clean/film_original_language")


def run_id():
    manifest = json.loads((CLEAN_DIR / "current.json").read_text("utf-8"))
    return str(manifest.get("run_id") or manifest.get("run") or "unknown-run")


def write(df, rid, name):
    """Write each result as a headered CSV directory under the run-specific output."""
    out = OUT / rid / name
    df.coalesce(1).write.mode("overwrite").option("header", True).csv(str(out))
    print(f"wrote {out}", flush=True)


def original_language_path():
    return Path(os.environ.get("ORIGINAL_LANGUAGE_PATH", str(DEFAULT_ORIGINAL_LANGUAGE_PATH)))


def main():
    language_path = original_language_path()
    if not language_path.exists():
        raise FileNotFoundError(
            "Q6 requires an original-language Parquet source with columns "
            "tconst and original_language. The Wikimedia streaming pipeline "
            "does not provide one. Supply it (TODO: identify a valid source) "
            f"or set ORIGINAL_LANGUAGE_PATH; current path: {language_path}"
        )

    spark = create_spark("exploration")
    try:
        p, rid = Params(), run_id()
        # Load only the cleaned IMDb tables used by these analyses. title.akas
        # is deliberately not used as an original-language proxy.
        tables = load_clean_tables(spark, names=(
            "title.basics", "title.ratings", "title.crew", "title.episode",
            "title.principals", "name.basics",
        ))
        basics, ratings = tables["title.basics"], tables["title.ratings"]
        crew, episodes = tables["title.crew"], tables["title.episode"]
        principals, names = tables["title.principals"], tables["name.basics"]
        original_language_table = spark.read.parquet(str(language_path))
        required = {"tconst", "original_language"}
        missing = required.difference(original_language_table.columns)
        if missing:
            raise ValueError(
                f"Original-language source {language_path} is missing columns: "
                f"{', '.join(sorted(missing))}"
            )

        write(A.compute_q1(basics, p), rid, "q1_runtime_outliers")
        stats = A.genre_year_stats(basics, ratings, p).cache()
        # Cardinality check: one row per (year, genre).
        assert stats.groupBy("startYear", "genre").count().filter("count > 1").limit(1).count() == 0
        write(A.compute_q2(stats, p), rid, "q2_top_genres")
        write(A.compute_q3(stats, p), rid, "q3_top_vs_rest")
        stats.unpersist()

        # Q4/Q5 use the patched analysis interfaces and their declared defaults.
        write(A.one_hit_directors(basics, ratings, crew, names), rid,
              "q4_one_hit_directors")
        write(A.declining_series(basics, ratings, episodes), rid,
              "q5_declining_series")

        q6_actors = A.multilingual_actors(
            basics, ratings, principals, original_language_table, names,
        )
        write(q6_actors, rid, "q6_multilingual_actors")
        # Restored Q6 subset output: actors/actresses with at least 3 languages.
        write(A.q6_actors_3plus_languages(q6_actors), rid,
              "q6_actors_3plus_languages")

        write(A.early_peak_actors(basics, ratings, principals, names), rid,
              "q7_early_peak_actors")
        per_person, per_combination = A.multi_talented(
            basics, ratings, crew, principals, names,
        )
        write(per_person, rid, "q8_multi_talented_people")
        write(per_combination, rid, "q8_multi_talented_combinations")
    finally:
        spark.stop()


if __name__ == "__main__":
    main()
